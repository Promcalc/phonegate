// Package code generates, extracts and hashes one-time verification codes.
package code

import (
	"crypto/rand"
	"crypto/sha256"
	"crypto/subtle"
	"encoding/binary"
	"errors"
	"regexp"
	"strings"
)

var ErrNoCode = errors.New("no code candidate")

const DefaultDigits = "0123456789"

var tokenRe = regexp.MustCompile(`[A-Za-z0-9]+`)

// Random returns a code of n characters from alphabet using crypto/rand.
func Random(n int, alphabet string) (string, error) {
	if n <= 0 || alphabet == "" || len(alphabet) > 256 {
		return "", ErrNoCode
	}
	out := make([]byte, n)
	// Rejection sampling avoids modulo bias. When the alphabet size divides
	// 256, every byte is accepted.
	limit := 256 - (256 % len(alphabet))
	buf := make([]byte, n*2)
	for i := 0; i < n; {
		if _, err := rand.Read(buf); err != nil {
			return "", err
		}
		for _, b := range buf {
			if limit != 256 && int(b) >= limit {
				continue
			}
			out[i] = alphabet[int(b)%len(alphabet)]
			i++
			if i == n {
				break
			}
		}
	}
	return string(out), nil
}

// RandomWords returns n words joined by "-" using crypto/rand. The word list
// must contain at least two entries.
func RandomWords(n int, words []string) (string, error) {
	if n <= 0 || len(words) < 2 {
		return "", ErrNoCode
	}
	out := make([]string, n)
	limit := 65536 - (65536 % len(words))
	var buf [2]byte
	for i := 0; i < n; i++ {
		for {
			if _, err := rand.Read(buf[:]); err != nil {
				return "", err
			}
			v := int(binary.BigEndian.Uint16(buf[:]))
			if v >= limit {
				continue
			}
			out[i] = strings.ToUpper(words[v%len(words)])
			break
		}
	}
	return strings.Join(out, "-"), nil
}

// Hash returns SHA-256 of the normalized code. Only the hash is stored.
func Hash(value string) []byte {
	sum := sha256.Sum256([]byte(Normalize(value)))
	return sum[:]
}

// EqualHash compares a stored hash with a submitted code in constant time.
func EqualHash(stored []byte, value string) bool {
	if len(stored) != sha256.Size {
		return false
	}
	sum := Hash(value)
	return subtle.ConstantTimeCompare(stored, sum[:]) == 1
}

// Normalize makes alphanumeric codes case-insensitive and removes surrounding
// whitespace. Codes generated by this package never contain spaces.
func Normalize(value string) string {
	return strings.ToUpper(strings.TrimSpace(value))
}

// Candidates extracts plausible code tokens from an incoming SMS. It is
// intentionally permissive: the caller compares candidates against active
// sessions, so unrelated numbers cannot verify anything by themselves.
func Candidates(text string, codeLength int) []string {
	seen := make(map[string]struct{})
	var out []string
	for _, token := range tokenRe.FindAllString(text, -1) {
		token = Normalize(token)
		if len(token) < 4 || len(token) > 32 {
			continue
		}
		if codeLength > 0 && len(token) != codeLength {
			// Long alphanumeric identifiers are common in SMS; keep only the
			// configured length to reduce noise. Very short tokens are ignored.
			continue
		}
		if _, ok := seen[token]; ok {
			continue
		}
		seen[token] = struct{}{}
		out = append(out, token)
	}
	return out
}

// Digits reports whether s contains only decimal digits.
func Digits(s string) bool {
	if s == "" {
		return false
	}
	for _, r := range s {
		if r < '0' || r > '9' {
			return false
		}
	}
	return true
}
